print(f"    같은 직선으로 200대 전부 채점: R² = {R2(x, y, w2, b2):.4f}  ← 200대로 배운 0.7989 보다 한참 아래")
print(f"    참고: 2대로 얻은 직선은 w={w2:.3f}, b={b2:.1f} / 200대로 얻은 직선은 w={w_gd:.3f}, b={b_gd:.1f}")

